-- CraveQuest MVP schema. PostgreSQL 15+.
-- This migration is intentionally additive and does not enable extensions.

CREATE TABLE outlets (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            text NOT NULL UNIQUE,
    name            text NOT NULL,
    cuisine_type    text NOT NULL,
    address_line    text NOT NULL,
    city            text NOT NULL,
    region          text NOT NULL,
    postal_code     text,
    country_code    char(2) NOT NULL,
    time_zone       text NOT NULL,
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT outlets_slug_not_blank CHECK (btrim(slug) <> ''),
    CONSTRAINT outlets_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT outlets_country_code_format CHECK (country_code ~ '^[A-Z]{2}$')
);

CREATE TABLE menus (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id       bigint NOT NULL REFERENCES outlets(id) ON DELETE CASCADE,
    name            text NOT NULL,
    service_period  text NOT NULL DEFAULT 'all_day',
    valid_from      date,
    valid_through   date,
    is_published    boolean NOT NULL DEFAULT false,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT menus_outlet_id_id_unique UNIQUE (outlet_id, id),
    CONSTRAINT menus_outlet_name_unique UNIQUE (outlet_id, name),
    CONSTRAINT menus_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT menus_valid_dates CHECK (valid_from IS NULL OR valid_through IS NULL OR valid_through >= valid_from)
);

CREATE TABLE dishes (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id               bigint NOT NULL REFERENCES outlets(id) ON DELETE CASCADE,
    name                    text NOT NULL,
    description             text,
    category                text NOT NULL,
    ingredient_data_status  text NOT NULL DEFAULT 'unknown',
    ingredient_data_source  text,
    ingredient_data_checked_at timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT dishes_outlet_id_id_unique UNIQUE (outlet_id, id),
    CONSTRAINT dishes_outlet_name_unique UNIQUE (outlet_id, name),
    CONSTRAINT dishes_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT dishes_ingredient_data_status CHECK (ingredient_data_status IN ('unknown', 'partial', 'verified_complete')),
    CONSTRAINT dishes_verified_data_has_evidence CHECK (
        ingredient_data_status <> 'verified_complete'
        OR (ingredient_data_source IS NOT NULL AND btrim(ingredient_data_source) <> '' AND ingredient_data_checked_at IS NOT NULL)
    )
);

-- A menu entry repeats outlet_id solely to make cross-outlet dish/menu links
-- impossible to insert (both composite foreign keys must match).
CREATE TABLE menu_dishes (
    outlet_id       bigint NOT NULL,
    menu_id         bigint NOT NULL,
    dish_id         bigint NOT NULL,
    price           numeric(10, 2) NOT NULL,
    currency_code   char(3) NOT NULL DEFAULT 'USD',
    availability_status text NOT NULL DEFAULT 'available',
    is_listed       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (menu_id, dish_id),
    -- Candidate key used by feedback to validate outlet, menu, and dish in one FK.
    CONSTRAINT menu_dishes_outlet_menu_dish_unique UNIQUE (outlet_id, menu_id, dish_id),
    CONSTRAINT menu_dishes_menu_outlet_fk FOREIGN KEY (outlet_id, menu_id)
        REFERENCES menus(outlet_id, id) ON DELETE CASCADE,
    CONSTRAINT menu_dishes_dish_outlet_fk FOREIGN KEY (outlet_id, dish_id)
        REFERENCES dishes(outlet_id, id) ON DELETE CASCADE,
    CONSTRAINT menu_dishes_price_nonnegative CHECK (price >= 0),
    CONSTRAINT menu_dishes_currency_format CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT menu_dishes_availability_status CHECK (availability_status IN ('available', 'sold_out', 'paused'))
);

-- Optional recurring service windows. If a menu entry has no windows, it is
-- available at any time while its menu is published and valid.
CREATE TABLE menu_dish_availability (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_id         bigint NOT NULL,
    dish_id         bigint NOT NULL,
    day_of_week     smallint NOT NULL,
    starts_at       time NOT NULL,
    ends_at         time NOT NULL,
    CONSTRAINT menu_dish_availability_entry_fk FOREIGN KEY (menu_id, dish_id)
        REFERENCES menu_dishes(menu_id, dish_id) ON DELETE CASCADE,
    CONSTRAINT menu_dish_availability_day CHECK (day_of_week BETWEEN 0 AND 6),
    CONSTRAINT menu_dish_availability_time CHECK (ends_at > starts_at),
    CONSTRAINT menu_dish_availability_unique UNIQUE (menu_id, dish_id, day_of_week, starts_at, ends_at)
);

CREATE TABLE ingredients (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL UNIQUE,
    CONSTRAINT ingredients_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE allergens (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text NOT NULL UNIQUE,
    CONSTRAINT allergens_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE ingredient_allergens (
    ingredient_id       bigint NOT NULL REFERENCES ingredients(id) ON DELETE CASCADE,
    allergen_id         bigint NOT NULL REFERENCES allergens(id) ON DELETE CASCADE,
    verification_status text NOT NULL DEFAULT 'unverified',
    evidence_note       text,
    verified_at         timestamptz,
    PRIMARY KEY (ingredient_id, allergen_id),
    CONSTRAINT ingredient_allergens_verification_status CHECK (verification_status IN ('verified', 'unverified')),
    CONSTRAINT ingredient_allergens_verified_has_evidence CHECK (
        verification_status <> 'verified'
        OR (evidence_note IS NOT NULL AND btrim(evidence_note) <> '' AND verified_at IS NOT NULL)
    )
);

CREATE TABLE dish_ingredients (
    dish_id             bigint NOT NULL REFERENCES dishes(id) ON DELETE CASCADE,
    ingredient_id       bigint NOT NULL REFERENCES ingredients(id) ON DELETE RESTRICT,
    presence_status     text NOT NULL DEFAULT 'contains',
    verification_status text NOT NULL DEFAULT 'unverified',
    evidence_note       text,
    verified_at         timestamptz,
    PRIMARY KEY (dish_id, ingredient_id),
    CONSTRAINT dish_ingredients_presence_status CHECK (presence_status IN ('contains', 'may_contain', 'free_from')),
    CONSTRAINT dish_ingredients_verification_status CHECK (verification_status IN ('verified', 'unverified')),
    CONSTRAINT dish_ingredients_verified_has_evidence CHECK (
        verification_status <> 'verified'
        OR (evidence_note IS NOT NULL AND btrim(evidence_note) <> '' AND verified_at IS NOT NULL)
    ),
    CONSTRAINT dish_ingredients_free_from_must_be_verified CHECK (
        presence_status <> 'free_from' OR verification_status = 'verified'
    )
);

CREATE TABLE dietary_tags (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            text NOT NULL UNIQUE,
    label           text NOT NULL,
    description     text,
    CONSTRAINT dietary_tags_slug_not_blank CHECK (btrim(slug) <> ''),
    CONSTRAINT dietary_tags_label_not_blank CHECK (btrim(label) <> '')
);

CREATE TABLE dish_dietary_tags (
    dish_id             bigint NOT NULL REFERENCES dishes(id) ON DELETE CASCADE,
    dietary_tag_id      bigint NOT NULL REFERENCES dietary_tags(id) ON DELETE RESTRICT,
    verification_status text NOT NULL DEFAULT 'unverified',
    evidence_note       text,
    verified_at         timestamptz,
    PRIMARY KEY (dish_id, dietary_tag_id),
    CONSTRAINT dish_dietary_tags_verification_status CHECK (verification_status IN ('verified', 'unverified')),
    CONSTRAINT dish_dietary_tags_verified_has_evidence CHECK (
        verification_status <> 'verified'
        OR (evidence_note IS NOT NULL AND btrim(evidence_note) <> '' AND verified_at IS NOT NULL)
    )
);

-- App-level profile only; identity and authentication are out of scope.
CREATE TABLE user_profiles (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name    text,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE user_preferences (
    user_id         bigint NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    dietary_tag_id  bigint NOT NULL REFERENCES dietary_tags(id) ON DELETE CASCADE,
    preference_level text NOT NULL DEFAULT 'prefer',
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, dietary_tag_id),
    CONSTRAINT user_preferences_level CHECK (preference_level IN ('prefer', 'require'))
);

CREATE TABLE user_restrictions (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    restriction_type text NOT NULL,
    dietary_tag_id  bigint REFERENCES dietary_tags(id) ON DELETE RESTRICT,
    ingredient_id   bigint REFERENCES ingredients(id) ON DELETE RESTRICT,
    allergen_id     bigint REFERENCES allergens(id) ON DELETE RESTRICT,
    severity        text,
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT user_restrictions_type CHECK (restriction_type IN ('allergy', 'intolerance', 'dietary')),
    CONSTRAINT user_restrictions_one_target CHECK (
        num_nonnulls(dietary_tag_id, ingredient_id, allergen_id) = 1
    ),
    CONSTRAINT user_restrictions_severity CHECK (severity IS NULL OR severity IN ('low', 'moderate', 'high', 'unknown')),
    CONSTRAINT user_restrictions_unique UNIQUE NULLS NOT DISTINCT (user_id, dietary_tag_id, ingredient_id, allergen_id)
);

CREATE TABLE recommendation_feedback (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    outlet_id       bigint NOT NULL,
    menu_id         bigint NOT NULL,
    dish_id         bigint NOT NULL,
    feedback        text NOT NULL,
    reason          text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT recommendation_feedback_menu_entry_fk FOREIGN KEY (outlet_id, menu_id, dish_id)
        REFERENCES menu_dishes(outlet_id, menu_id, dish_id) ON DELETE RESTRICT,
    CONSTRAINT recommendation_feedback_type CHECK (feedback IN ('liked', 'disliked', 'not_interested', 'tried'))
);

CREATE TABLE confirmed_discoveries (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         bigint NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    dish_id         bigint NOT NULL REFERENCES dishes(id) ON DELETE RESTRICT,
    confirmed_at    timestamptz NOT NULL DEFAULT now(),
    notes           text,
    UNIQUE (user_id, dish_id)
);

CREATE INDEX menus_outlet_published_idx ON menus(outlet_id, is_published);
CREATE INDEX dishes_outlet_category_idx ON dishes(outlet_id, category);
CREATE INDEX menu_dishes_recommendable_idx ON menu_dishes(outlet_id, availability_status, menu_id)
    WHERE is_listed = true;
CREATE INDEX menu_dish_availability_lookup_idx ON menu_dish_availability(day_of_week, starts_at, ends_at);
CREATE INDEX dish_ingredients_ingredient_idx ON dish_ingredients(ingredient_id, dish_id);
CREATE INDEX ingredient_allergens_allergen_idx ON ingredient_allergens(allergen_id, ingredient_id);
CREATE INDEX dish_dietary_tags_tag_idx ON dish_dietary_tags(dietary_tag_id, dish_id);
CREATE INDEX user_restrictions_user_idx ON user_restrictions(user_id);
CREATE INDEX recommendation_feedback_user_created_idx ON recommendation_feedback(user_id, created_at DESC);
CREATE INDEX recommendation_feedback_outlet_created_idx ON recommendation_feedback(outlet_id, created_at DESC);
CREATE INDEX confirmed_discoveries_user_confirmed_idx ON confirmed_discoveries(user_id, confirmed_at DESC);
